import { useState } from 'react'
import type { Project } from '../api'
import { Badge, Card, CredBadge, Markdown, SectionTitle } from '../ui'
import { PaperLinks } from './PapersView'

export default function ReportView({ p }: { p: Project }) {
  const [showChecks, setShowChecks] = useState(false)
  const r = p.report
  if (!r) return <p className="text-muted">The report is written last, after the Chamber rules.</p>
  const c = r.citations
  const cited = [...new Set((r.markdown.match(/P\d+/g) ?? []))]
  const papers = p.papers.filter((x) => cited.includes(x.id))
  return (
    <div className="grid gap-6 lg:grid-cols-[1fr_380px]">
      <Card className="p-8">
        <h1 className="font-display text-4xl leading-tight">{r.title}</h1>
        <div className="mt-4 rounded-xl bg-sunken p-4 text-[15px]"><Markdown text={r.tldr} className="[&_p]:m-0" /></div>
        <Markdown text={r.markdown} className="mt-4 text-[15px]" />
        <p className="mt-8 text-xs text-muted">Generated by GreenLight Research agents from the papers listed. Check the sources before relying on it.</p>
      </Card>
      <div className="space-y-6">
        <Card className="p-6">
          <SectionTitle>Citation check</SectionTitle>
          <div className="grid grid-cols-3 gap-2 text-center text-sm">
            <div className="rounded-xl bg-go-soft p-2 text-go"><div className="text-2xl font-semibold">{c.supported}</div>supported</div>
            <div className="rounded-xl bg-wait-soft p-2 text-wait"><div className="text-2xl font-semibold">{c.partial}</div>partial</div>
            <div className="rounded-xl bg-stop-soft p-2 text-stop"><div className="text-2xl font-semibold">{c.unsupported}</div>unsupported</div>
          </div>
          <p className="mt-3 text-xs text-muted">Each sentence citing a paper was judged against passages retrieved from that paper. Unsupported sentences are marked ⚠️ in the report.</p>
          <button onClick={() => setShowChecks(!showChecks)} className="mt-2 text-xs text-info underline">{showChecks ? 'Hide' : 'Show'} all {c.claims.length} checks</button>
          {showChecks && (
            <div className="scroll-thin mt-3 max-h-96 space-y-2 overflow-y-auto">
              {c.claims.map((x, i) => (
                <div key={i} className="rounded-lg bg-sunken p-2 text-xs">
                  <Badge tone={x.label === 'supported' ? 'go' : x.label === 'partial' ? 'wait' : x.label === 'unsupported' ? 'stop' : 'neutral'}>{x.label}</Badge>
                  <div className="mt-1"><Markdown text={x.text} className="[&_p]:m-0" /></div>
                  {x.why && <div className="mt-1 text-muted">{x.why}</div>}
                </div>
              ))}
            </div>
          )}
        </Card>
        <Card className="p-6">
          <SectionTitle>References ({papers.length})</SectionTitle>
          <div className="space-y-4">
            {papers.map((x) => (
              <div key={x.id} className="text-sm">
                <div className="flex items-center gap-2"><span className="font-mono text-xs text-info">{x.id}</span><CredBadge c={x.credibility} /></div>
                <div className="mt-1 leading-snug">{x.title}</div>
                <div className="mb-1.5 text-xs text-muted">{x.authors.slice(0, 3).join(', ')}{x.n_authors > 3 ? ' et al.' : ''} · {x.year}{x.venue ? ` · ${x.venue}` : ''}</div>
                <PaperLinks p={x} />
              </div>
            ))}
          </div>
        </Card>
      </div>
    </div>
  )
}
